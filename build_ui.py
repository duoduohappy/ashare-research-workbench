"""Build the checked-in browser bundle, compatible with legacy static routes."""
import argparse
from pathlib import Path

ROOT=Path(__file__).resolve().parent
SOURCES=('ui/advanced_core.js','factor_validation.js','portfolio_optimization.js','regime_research.js','strategy_validation.js','research_evidence.js','point_in_time.js')


def render():
    parts=['// Generated by python build_ui.py; edit source files, not this bundle.\n']
    for name in SOURCES:
        parts.append('\n// Source: '+name+'\n'+(ROOT/name).read_text(encoding='utf-8').rstrip()+'\n')
    return ''.join(parts)


if __name__=='__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args();target=ROOT/'advanced.js';expected=render()
    if args.check:
        if not target.exists() or target.read_text(encoding='utf-8')!=expected:
            raise SystemExit('Browser bundle is stale; run python build_ui.py')
        print('Browser bundle matches all sources')
    else:
        temporary=target.with_name('advanced.build.tmp')
        temporary.write_bytes(expected.encode('utf-8'))
        temporary.replace(target)
        print('Built advanced.js from '+str(len(SOURCES))+' sources')
